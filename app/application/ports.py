"""Ports the application layer depends on. Infrastructure provides the adapters."""
from __future__ import annotations

from typing import Protocol

from app.domain.models import Agent, Area, QualitySettings, Task


class LlmError(Exception):
    """The model call failed. The message is safe to show to the user."""


class LlmGateway(Protocol):
    async def generate_text(self, system: str, prompt: str) -> str: ...

    async def generate_structured(self, system: str, prompt: str, schema: dict) -> dict: ...

    def describe(self) -> dict: ...


class OfficeRepository(Protocol):
    def list_areas(self) -> list[Area]: ...
    def get_area(self, area_id: int) -> Area: ...
    def save_area(self, area: Area) -> None: ...

    def list_agents(self) -> list[Agent]: ...
    def get_agent(self, agent_id: str) -> Agent: ...
    def save_agent(self, agent: Agent) -> None: ...
    def delete_agent(self, agent_id: str) -> None: ...

    def list_tasks(self) -> list[Task]: ...
    def get_task(self, task_id: str) -> Task: ...
    def save_task(self, task: Task) -> None: ...

    def get_settings(self) -> QualitySettings: ...
    def save_settings(self, settings: QualitySettings) -> None: ...
